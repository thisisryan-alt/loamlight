CELL_W, CELL_H = 8, 10
COLS = 16
ASCENT, DESCENT = 7, 2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    chars = [chr(c) for c in range(32, 127)]
    missing = [c for c in chars if c not in G]
    if missing:
        raise SystemExit(f"[gen_font] missing glyphs: {''.join(missing)}")
    rows = (len(chars) + COLS - 1) // COLS
    W, H = COLS * CELL_W, 64
    img = np.zeros((H, W, 4), dtype=np.uint8)
    meta = {"version": 1, "width": W, "height": H, "ascent": ASCENT, "descent": DESCENT, "lineHeight": 10, "fontSize": 8, "glyphs": []}
    for i, ch in enumerate(chars):
        rows_ = G[ch]
        width = max(len(r) for r in rows_[:9]) if ch != " " else 3
        cx, cy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        for ry, row in enumerate(rows_[:9]):
            for rx, c in enumerate(row):
                if c == "#":
                    img[cy + ry, cx + rx] = (255, 255, 255, 255)
        # rect in image space (top-left origin); the Unity importer flips to UV space
        meta["glyphs"].append({"char": ord(ch), "x": cx, "y": cy, "w": width, "h": ASCENT + DESCENT, "advance": width + 1})
    os.makedirs(args.out, exist_ok=True)
    Image.fromarray(img, "RGBA").save(os.path.join(args.out, "pixelfont.png"), optimize=False, compress_level=9)
    with open(os.path.join(args.out, "pixelfont.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(meta, f, indent=1)
        f.write("\n")
    print(f"[gen_font] {len(chars)} glyphs -> {args.out}")


if __name__ == "__main__":
    main()
